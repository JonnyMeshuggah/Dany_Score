// Приветствие по времени суток (часы 0–23)
export function greeting(hour) {
  if (hour >= 5 && hour < 12) return "Доброе утро";
  if (hour >= 12 && hour < 17) return "Добрый день";
  if (hour >= 17 && hour < 23) return "Добрый вечер";
  return "Доброй ночи";
}

export function formatReward(reward) {
  if (typeof reward !== "number" || reward === 0) return "";
  return `${reward > 0 ? "+" : "−"}${Math.abs(reward)} ₽`;
}

// Вид реплики и настроение дроида после добавления оценки.
// entry — запись из applyGrade ({ grade, reward, bonus, subject }), tasksDone — сколько заданий пропуска закрыла оценка.
export function gradeReaction(entry, tasksDone = 0) {
  const vars = { reward: formatReward(entry.reward), subject: entry.subject, bonus: entry.bonus || "" };
  if (tasksDone > 0) return { kind: "task", mood: "party", vars };
  if (entry.grade === 5 && entry.bonus) return { kind: "combo", mood: "party", vars };
  if (entry.grade === 5) return { kind: "five", mood: "party", vars };
  if (entry.grade === 4) return { kind: "four", mood: "happy", vars };
  if (entry.grade === 3) return { kind: "three", mood: "oops", vars };
  if (entry.grade === 2) return { kind: "two", mood: "oops", vars };
  return { kind: "joke", mood: "talk", vars };
}

export function fillLine(template, vars = {}) {
  const all = { name: BUDDY_NAME, ...vars };
  return template.replace(/\{(\w+)\}/g, (_, key) => (all[key] ?? ""));
}

// Реплика вида kind, не повторяющая предыдущую того же вида: { text, index }
export function pickLine(kind, vars, prevIndex, random = Math.random) {
  const pool = LINES[kind] || LINES.joke;
  const index = pickQuoteIndex(pool.length, prevIndex, random);
  return { text: fillLine(pool[index], vars), index };
}
