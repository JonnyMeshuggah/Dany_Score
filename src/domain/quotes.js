// Индекс случайной цитаты, отличной от предыдущей (prev) — чтобы при следующем входе не повторилась.
export function pickQuoteIndex(count, prev, random = Math.random) {
  if (count <= 1) return 0;
  const hasPrev = Number.isInteger(prev) && prev >= 0 && prev < count;
  const i = Math.floor(random() * (hasPrev ? count - 1 : count));
  return hasPrev && i >= prev ? i + 1 : i;
}
